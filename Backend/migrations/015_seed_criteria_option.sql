INSERT IGNORE INTO criteria_option (dimension_id, code, label, sort_order)
SELECT d.id, seeded.code, seeded.label, seeded.sort_order
FROM criteria_dimension d
JOIN (
  SELECT 'MARITAL_STATUS' AS dimension_code, 'NEVER_MARRIED' AS code, 'Never married' AS label, 10 AS sort_order
  UNION ALL SELECT 'MARITAL_STATUS', 'MARRIED', 'Married', 20
  UNION ALL SELECT 'MARITAL_STATUS', 'WIDOWED', 'Widowed', 30
  UNION ALL SELECT 'MARITAL_STATUS', 'DIVORCED', 'Divorced', 40
  UNION ALL SELECT 'MARITAL_STATUS', 'SEPARATED', 'Separated', 50
  UNION ALL SELECT 'RESIDENCE_TYPE', 'RURAL', 'Rural', 10
  UNION ALL SELECT 'RESIDENCE_TYPE', 'URBAN', 'Urban', 20
  UNION ALL SELECT 'SOCIAL_CATEGORY', 'GENERAL', 'General', 10
  UNION ALL SELECT 'SOCIAL_CATEGORY', 'OBC', 'OBC', 20
  UNION ALL SELECT 'SOCIAL_CATEGORY', 'SC', 'SC', 30
  UNION ALL SELECT 'SOCIAL_CATEGORY', 'ST', 'ST', 40
  UNION ALL SELECT 'SOCIAL_CATEGORY', 'EWS', 'EWS', 50
  UNION ALL SELECT 'DISABILITY_STATUS', 'YES', 'Has a disability', 10
  UNION ALL SELECT 'DISABILITY_STATUS', 'NO', 'Does not have a disability', 20
  UNION ALL SELECT 'WORK_STATUS', 'STUDENT', 'Student', 10
  UNION ALL SELECT 'WORK_STATUS', 'EMPLOYED', 'Employed', 20
  UNION ALL SELECT 'WORK_STATUS', 'SELF_EMPLOYED', 'Self-employed', 30
  UNION ALL SELECT 'WORK_STATUS', 'UNEMPLOYED', 'Unemployed', 40
  UNION ALL SELECT 'EMPLOYMENT_TYPE', 'GOVERNMENT', 'Government', 10
  UNION ALL SELECT 'EMPLOYMENT_TYPE', 'PRIVATE', 'Private', 20
  UNION ALL SELECT 'OCCUPATION', 'AGRICULTURE', 'Agriculture', 10
  UNION ALL SELECT 'OCCUPATION', 'TEACHING', 'Teaching', 20
  UNION ALL SELECT 'OCCUPATION', 'TAILORING', 'Tailoring', 30
  UNION ALL SELECT 'OCCUPATION', 'STREET_VENDING', 'Street vending', 40
  UNION ALL SELECT 'OCCUPATION', 'OTHER', 'Other', 50
  UNION ALL SELECT 'BPL_CARD', 'YES', 'Has a BPL card', 10
  UNION ALL SELECT 'BPL_CARD', 'NO', 'Does not have a BPL card', 20
) AS seeded ON seeded.dimension_code = d.code
WHERE d.input_type IN ('SINGLE_SELECT', 'MULTI_SELECT');
