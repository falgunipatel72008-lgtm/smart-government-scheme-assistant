type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string, values?: Record<string, string | number>) => string;
  categoryName: (name: string) => string;
  categoryDescription: (description: string) => string;
  ministryName: (name: string) => string;
  locationName: (name: string) => string;
  schemeName: (code: string | null, name: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function isLanguage(value: string | null): value is Language {
  return value === "en" || value === "hi" || value === "gu";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return isLanguage(savedLanguage) ? savedLanguage : "en";
  });

  useEffect(() => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (nextLanguage: Language) => setLanguageState(nextLanguage);
  const t = (text: string, values?: Record<string, string | number>) => {
    const translated = language === "en" ? text : translations[language][text] ?? text;
    if (!values) return translated;
    return translated.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
  };
  const categoryName = (name: string) => {
    if (language === "en") return name;
    const translated = categoryTranslations[name];
    return translated ? translated[language === "hi" ? 0 : 1] : name;
  };
  const categoryDescription = (description: string) => {
    if (language === "en") return description;
    const translated = categoryDescriptionTranslations[description];
    return translated ? translated[language === "hi" ? 0 : 1] : description;
  };
  const ministryName = (name: string) => {
    if (language === "en") return name;
    const translated = ministryTranslations[name];
    return translated ? translated[language === "hi" ? 0 : 1] : name;
  };
  const locationName = (name: string) => {
    if (language === "en") return name;
    const translated = locationTranslations[name];
    return translated ? translated[language === "hi" ? 0 : 1] : name;
  };
  const schemeName = (code: string | null, name: string) => {
    if (language === "en" || !code) return name;
    const translated = schemeNames[code];
    return translated ? translated[language === "hi" ? 0 : 1] : name;
  };

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, categoryName, categoryDescription, ministryName, locationName, schemeName }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}
